#!/usr/bin/env node
// Writes .forge/design-index.json: the requirement keys and the workflow steps of the Forge project,
// read from a Forge instance's API. check-module-shape validates every `serves` entry in
// packages/core/src/modules.json against this committed snapshot, so verify makes no network call.
// Re-run it after a requirement or a workflow step is added, renamed or dropped.
//
//   FORGE_TOKEN=<pat> node scripts/refresh-design-index.mjs
//   FORGE_API_URL (default https://forge-dev-api.sidcorp.co), FORGE_PROJECT_ID (default the
//   forge project on that instance)

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { dieAs, ROOT } from './lib/gate.mjs';

const die = dieAs('design-index');

const OUT = '.forge/design-index.json';
const API = (process.env.FORGE_API_URL ?? 'https://forge-dev-api.sidcorp.co').replace(/\/$/, '');
const PROJECT = process.env.FORGE_PROJECT_ID ?? 'd1bb4907-74d9-4228-85ff-76121523af7d';
const TOKEN = process.env.FORGE_TOKEN;

if (!TOKEN) die('FORGE_TOKEN is unset; a personal access token with project.read is needed');

async function get(path) {
  const res = await fetch(`${API}${path}`, {
    headers: {
      Accept: 'application/json',
      Authorization: `Bearer ${TOKEN}`,
      'User-Agent': 'curl/8.5.0',
      'X-Forge-Lifecycle': '10',
    },
  });
  if (!res.ok) die(`GET ${path} answered ${res.status}: ${(await res.text()).slice(0, 300)}`);
  return res.json();
}

const reqs = await get(`/api/projects/${PROJECT}/requirements`);
const flows = await get(`/api/projects/${PROJECT}/workflows`);
for (const [name, body, list] of [
  ['requirements', reqs, reqs.requirements],
  ['workflows', flows, flows.workflows],
]) {
  if (!Array.isArray(list)) die(`${name} answered no list`);
  if (body.next || body.nextCursor) die(`${name} is paginated; this script reads one page only`);
}

const requirements = Object.fromEntries(
  reqs.requirements
    .map((r) => [r.key, { title: r.title, status: r.status }])
    .sort((a, b) => Number(a[0].slice(4)) - Number(b[0].slice(4))),
);
const workflows = Object.fromEntries(
  flows.workflows
    .map((w) => [
      w.document.flow,
      { title: w.document.title, steps: (w.document.steps ?? []).map((s) => s.id).sort() },
    ])
    .sort((a, b) => a[0].localeCompare(b[0])),
);

const doc = {
  $comment:
    'Generated by scripts/refresh-design-index.mjs; do not edit. The requirement keys and workflow steps a `serves` entry in packages/core/src/modules.json may name.',
  source: { api: API, projectId: PROJECT },
  requirements,
  workflows,
};
writeFileSync(join(ROOT, OUT), `${JSON.stringify(doc, null, 1)}\n`);
console.log(
  `design-index: wrote ${OUT}: ${Object.keys(requirements).length} requirement(s), ${Object.keys(workflows).length} workflow(s)`,
);
