// The REST writes no agent reaches for, so none carries a capability card (ISS-1251 c1). A door is
// agent-facing where an agent calls it or is taught to: a bot, a master, a run or the steward called
// it on forge (door-use, 2026-10-17..11-16), or a guide, the drive rules, the orientation, a room
// brief, the forge-runner CLI or the forge plugin's CLI names it. Every other REST write is declared
// here by its exact id and why, and `cards.test.ts` holds the two apart: a served write is carded,
// twinned to a carded action, or declared here, never two of them, so a new door an agent is meant
// to call fails the build until it is carded or declared.

/** Why a REST write carries no card. */
export const UNCARDED_WHY = {
  person:
    "a person's own door: on forge (2026-10-17..11-16) only a person's credential called it, and no text an agent reads teaches it",
  machine:
    "called by code, never by a model: the runner daemon on a paired box, a host's webhook, Prometheus, or an MCP client's transport and sign-in",
  retired: 'retired: it answers AGENT_REPORT_RETIRED, naming the door that replaced it',
  gateway:
    "posted by core's own code around an agent's session (the steward gateway's decisions, the room box's git helper), never by the model",
} as const;

