/**
 * The line every generated orientation carries under its heading. The runner reads it
 * (`runner-workspace/src/orientation.rs:is_generated`) to tell an orientation Forge wrote from one a
 * person did, and refuses to write a body that lacks it.
 */
export const ORIENTATION_GENERATED_LINE =
  '<!-- Generated by Forge on device provision. Forge-owned; manual edits are overwritten. -->';

/**
 * The project's always-applied rules as an orientation reads them: its `injection: 'always'`
 * knowledge entries, or `unreadable` where the knowledge store could not be read.
 */
export type OrientationRules =
  | {
      entries: readonly AlwaysInjectFact[];
      lessons?: readonly LessonEntry[];
      /** The on-demand slugs of the project and of its org it does not shadow (ISS-867). */
      guides?: {
        project: readonly string[];
        org: readonly string[];
        /** What each rests on, by slug (ISS-1064). */
        sources?: Readonly<Record<string, string | null>>;
      };
      /** The project's working agreements, resolved for no task (REQ-90). */
      agreements?: AgreementsView;
      /**
       * By card id, the situations this project's lessons folded into an orientation card that its
       * code does not carry yet (ISS-1251), shown in the table as proposed.
       */
      proposed?: ReadonlyMap<string, readonly string[]>;
      /** The project's module lines, one per business module (ISS-1256), its master's Tier-0 map of them. */
      modules?: readonly ModuleMapLine[];
    }
  | { unreadable: true };

/** The rules block, or a named absence: a box told nothing would read a project with no rules. */
function rulesText(projectId: string, rules: OrientationRules): string | null {
  if ('unreadable' in rules)
    return `## Project rules (always applied)

The project's knowledge could not be read when this orientation was written, so its rules and working agreements are not here. Read them before you work: \`GET /api/projects/${projectId}/knowledge?injection=always\` and \`GET /api/projects/${projectId}/agreements\`.`;
  // a master and the runs it declares build issues, breakdowns, designs and revisions, and work
  // across areas, so the map names every area lesson labelled with its area (REQ-50 BC-3)
  const lessons = lessonsMapText(
    rules.lessons ?? [],
    {
      produces: ['issue', 'suggestion', 'requirement', 'workflow'],
      area: 'any',
      ...restLessonDoors(projectId),
    },
    2,
  );
  const always = new Set(rules.entries.map((e) => e.key));
  const guides = guideIndexText({
    projectId,
    project: (rules.guides?.project ?? []).filter((s) => !always.has(s)),
    org: rules.guides?.org ?? [],
    sources: rules.guides?.sources,
    read: (path) => `\`forge-runner api ${path}\``,
    depth: 2,
  });
  const parts = [
    rules.agreements ? agreementsMapText(rules.agreements, 2, projectId) : null,
    rules.entries.length > 0
      ? projectRulesText(
          rules.entries,
          2,
          rules.agreements ? restatedRules(rules.agreements) : undefined,
        )
      : null,
    lessons,
    guides,
  ].filter((p): p is string => p !== null);
  return parts.length > 0 ? parts.join('\n\n') : null;
}

/**
 * The orientation a box writes into a checkout of project `slug` for a person's `claude` session
 * and for every run a master declares there, served on every provision and assignment read so the
 * box writes what it is sent. The affordances table is the one pipeline prompts carry
 * (`OPERATING_AFFORDANCES_TEXT`), and the project's always-applied knowledge entries are the block a
 * pipeline preamble carries (`projectRulesText`), so neither can drift from what a core-built prompt
 * says (REQ-43 BC-12). Deterministic for a project and its rules, so a re-provision writes
 * byte-identical output.
 */
export function checkoutOrientation(
  projectId: string,
  slug: string,
  rules: OrientationRules,
): string {
  const projectRules = rulesText(projectId, rules);
  return `# Forge orientation — ${slug}

${ORIENTATION_GENERATED_LINE}

This repo is managed by **Forge** — the control plane for its issues, pipeline, and durable
memory. Reach it through the REST API (\`forge-runner api <path>\`) or the \`forge\` CLI; the Forge MCP
server in \`.mcp.json\` carries only what neither covers, and its instructions name those tools.

- **projectId:** \`${projectId}\`  ·  **slug:** \`${slug}\`
- **Before you design or fix, recall what earlier work settled** — memory is not loaded for you:
  \`POST /api/memory/search { "projectId": "${projectId}", "query": <topic>, "topK": 5 }\`. A hit is
  point-in-time: an \`unverified\` \`standing\` is a lead to check against live code/git, never a fact.
- **When you need the project's own words** (build commands, a rule, a guide):
  \`GET /api/projects/${projectId}/knowledge\` or \`forge knowledge\`.
- **When you work an issue**, read it, its comments and its edges first: \`/api/issues/<id>\`
  (\`forge issue\`, \`forge comment\`); the project's list is \`/api/projects/${projectId}/issues\`.
- **When a Forge door, guide or skill fails you** (it refused what it should take, missed what you
  needed, or taught you wrong), say so: \`POST /api/forge/feedback/doors { verdict, door, what }\`
  (\`did_not_help\`, \`unclear\` or \`missing\`) files it on the feature that owns the door.
- **Before you write or tune this project's pipeline skills**, read the \`forge-skills\` MCP prompt.

${operatingAffordancesText('unreadable' in rules ? undefined : rules.proposed)}
${modulesBlock(rules)}${projectRules ? `\n${projectRules.trimEnd()}\n` : ''}`;
}

/** The module lines, as their own block after the affordances; nothing where the project has none. */
function modulesBlock(rules: OrientationRules): string {
  if ('unreadable' in rules || !rules.modules) return '';
  const text = moduleLinesText(rules.modules, 'master');
  return text ? `\n${text}\n` : '';
}

/**
 * The orientation core serves a box for project `slug`, its rules read from the knowledge store. A
 * store that cannot be read is said in the orientation rather than failing the box's whole read,
 * which also carries which projects route to it.
 */
export async function servedCheckoutOrientation(projectId: string, slug: string): Promise<string> {
  let rules: OrientationRules;
  try {
    const [entries, lessons, project, org, sources, agreements, proposed, modules] =
      await Promise.all([
        selectAlwaysInjectFromKnowledge(projectId),
        selectLessonEntries(projectId),
        selectOnDemandSlugsFromKnowledge(projectId),
        orgOnDemandSlugsOf(projectId),
        selectOnDemandSourcesFromKnowledge(projectId),
        readAgreements(projectId, null),
        proposedSituationsOrUnknown(projectId),
        moduleMapLines(projectId),
      ]);
    rules = {
      entries,
      lessons,
      guides: { project, org, sources },
      agreements,
      ...(proposed ? { proposed } : {}),
      modules,
    };
  } catch (err) {
    logger.error(
      { err: (err as Error).message, projectId },
      'checkout orientation: knowledge store unreadable, the orientation says so in place of the rules',
    );
    rules = { unreadable: true };
  }
  return checkoutOrientation(projectId, slug, rules);
}

/**
 * The proposed situations, or none known where the card ledger cannot be read: the ledger is not
 * the knowledge store, so its failure costs the table its proposed rows and never the project's rules.
 */
async function proposedSituationsOrUnknown(
  projectId: string,
): Promise<Map<string, string[]> | undefined> {
  try {
    return await proposedSituations(projectId);
  } catch (err) {
    logger.error(
      { err: (err as Error).message, projectId },
      'checkout orientation: the card ledger is unreadable, so no proposed situation is shown and the rules are served',
    );
    return undefined;
  }
}

/** The situations this project's lessons folded into the orientation's cards, by card id. */
async function proposedSituations(projectId: string): Promise<Map<string, string[]>> {
  const fresh = await cardFreshness(AFFORDANCE_CARDS.map((c) => c.id));
  return new Map(
    fresh.map((f) => [
      f.cardId,
      f.proposedDeltas
        .filter(
          (d) => d.field === 'situation' && (d.projectId === null || d.projectId === projectId),
        )
        .map((d) => d.text),
    ]),
  );
}
