#!/usr/bin/env node
// Embeds src/guides/content/<slug>.md as src/guides/content.generated.ts, so the bodies ship in
// `dist`. Same shape as web-v2's gen-help-content.mjs, minus front-matter: registry.ts keeps a
// guide's metadata. `--check` refuses a stale module; `--from <dir> --to <file>` redirect a test.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const flag = (name) => {
  const at = process.argv.indexOf(name);
  return at === -1 ? null : path.resolve(process.argv[at + 1] ?? '');
};
const CONTENT_DIR = flag('--from') ?? path.join(root, 'src', 'guides', 'content');
const OUT_FILE = flag('--to') ?? path.join(root, 'src', 'guides', 'content.generated.ts');
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

const refused = [];
const bodies = {};
for (const entry of (await fs.readdir(CONTENT_DIR, { withFileTypes: true })).sort((a, b) =>
  a.name.localeCompare(b.name),
)) {
  const where = path.relative(root, path.join(CONTENT_DIR, entry.name)).replaceAll('\\', '/');
  if (!entry.isFile() || !entry.name.endsWith('.md')) {
    refused.push(`${where}: only <slug>.md files belong in this folder`);
    continue;
  }
  const slug = entry.name.slice(0, -'.md'.length);
  if (!SLUG.test(slug)) {
    refused.push(`${where}: "${slug}" is not a slug (lowercase words joined by hyphens)`);
    continue;
  }
  const body = await fs.readFile(path.join(CONTENT_DIR, entry.name), 'utf8');
  if (body.trim() === '') refused.push(`${where}: the body is empty`);
  else if (body.includes('\r')) {
    // The served bytes are the file's bytes; a checkout that rewrites line endings would change them.
    refused.push(`${where}: carries a carriage return, and the served bytes are the file's bytes`);
  } else bodies[slug] = body;
}
if (refused.length > 0) {
  console.error(`gen-guide-content: refused ${refused.length} file(s):\n  ${refused.join('\n  ')}`);
  process.exit(1);
}

const out =
  '// AUTO-GENERATED by scripts/gen-guide-content.mjs from src/guides/content/. Do not edit.\n' +
  '// Run `pnpm gen:guides` (it runs automatically on dev and build).\n' +
  // A body may quote `${NAME}`; as \u0024 it stays a plain string to any reader of this file
  // instead of looking like a template literal nobody interpolated.
  `export const GUIDE_CONTENT: Readonly<Record<string, string>> = ${JSON.stringify(bodies, null, 2).replaceAll('${', '\\u0024{')};\n`;

const count = Object.keys(bodies).length;
if (process.argv.includes('--check')) {
  const committed = await fs.readFile(OUT_FILE, 'utf8').catch(() => null);
  if (committed !== out) {
    console.error(
      `gen-guide-content: ${path.relative(root, OUT_FILE)} does not match src/guides/content/ — run \`pnpm gen:guides\` and commit it`,
    );
    process.exit(1);
  }
  console.log(`gen-guide-content: ${count} bodies, ${path.relative(root, OUT_FILE)} is current`);
} else {
  await fs.writeFile(OUT_FILE, out, 'utf8');
  console.log(`gen-guide-content: wrote ${count} bodies → ${path.relative(root, OUT_FILE)}`);
}
