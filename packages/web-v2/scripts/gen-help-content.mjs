#!/usr/bin/env node
// Generate a bundled TS module from the end-user help docs in content/help/.
// Markdown → a static module the web app imports, so the content ships inside
// the Next build (no runtime fs, no API, no output-tracing needed under
// `output: standalone`). Run by `dev`/`build` (see package.json). Skips README.md
// (the authoring-rules doc) and refuses, by name, any other file without frontmatter.
// `--check` writes nothing and refuses a bundled module that no longer matches content/help/, so a
// page edited without regenerating is red in the suite rather than wrong in the next build;
// `--from <dir>` reads another folder, for a test to plant one (ISS-1421 r41, judge-167).

import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { readAudience, readPage } from "./help-frontmatter.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const fromAt = process.argv.indexOf("--from");
const CONTENT_DIR = fromAt > 0 ? path.resolve(process.argv[fromAt + 1]) : path.join(root, "content", "help");
const CHECK = process.argv.includes("--check");
const OUT_FILE = path.join(root, "src", "features", "docs", "help-content.generated.ts");
// The slugs alone, for the middleware, which would otherwise bundle every page body to learn them.
const SLUGS_FILE = path.join(root, "src", "features", "docs", "help-slugs.generated.ts");

async function walk(dir) {
  const out = [];
  for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
    const abs = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(abs)));
    else if (/\.mdx?$/i.test(entry.name) && entry.name.toLowerCase() !== "readme.md") {
      out.push(abs);
    }
  }
  return out;
}

const files = await walk(CONTENT_DIR);
const docs = [];
const refused = [];
// Each page's own file by its slug, so a stale bundle names the page that drifted (ISS-1421 r42).
const fileOf = {};
for (const abs of files.sort()) {
  const raw = await fs.readFile(abs, "utf8");
  const slug = path
    .relative(CONTENT_DIR, abs)
    .replace(/\\/g, "/")
    .replace(/\.mdx?$/i, "");
  let parsed;
  let audience;
  try {
    parsed = readPage(raw, path.relative(root, abs));
    audience = readAudience(parsed.meta, path.relative(root, abs));
  } catch (err) {
    refused.push(err.message);
    continue;
  }
  fileOf[slug] = path.relative(root, abs);
  docs.push({
    slug,
    title: parsed.meta.title ?? slug,
    section: parsed.meta.section ?? "Guides",
    order: Number(parsed.meta.order ?? 100),
    audience,
    body: parsed.body,
  });
}
if (refused.length > 0) {
  console.error(`gen-help-content: refused ${refused.length} page(s):\n  ${refused.join("\n  ")}`);
  process.exit(1);
}

const banner =
  "// AUTO-GENERATED by scripts/gen-help-content.mjs from content/help/. Do not edit.\n" +
  "// Run `pnpm gen:help` (or it runs automatically on dev/build).\n";
const out =
  banner +
  "export interface HelpDoc {\n" +
  "  slug: string;\n  title: string;\n  section: string;\n  order: number;\n" +
  '  audience: "user" | "assistant-setup";\n  body: string;\n' +
  "}\n\n" +
  // A page may quote `${NAME}` (a config the reader pastes); as \u0024 it stays a plain string
  // to any reader of this file instead of looking like a template literal nobody interpolated.
  `export const HELP_DOCS: HelpDoc[] = ${JSON.stringify(docs, null, 2).replaceAll("${", "\\u0024{")};\n`;

/** The pages whose bundled copy differs from their file, added or removed, read off the committed
 *  module: ": what-done-means.md changed". Empty where that module cannot be read as one. */
async function driftedPages() {
  const committed = await fs.readFile(OUT_FILE, "utf8").catch(() => "");
  const start = committed.indexOf("export const HELP_DOCS: HelpDoc[] = ");
  if (start < 0) return "";
  let bundled;
  try {
    bundled = JSON.parse(committed.slice(start + "export const HELP_DOCS: HelpDoc[] = ".length).replace(/;\s*$/, ""));
  } catch {
    return "";
  }
  const was = new Map(bundled.map((d) => [d.slug, JSON.stringify(d)]));
  const now = new Map(docs.map((d) => [d.slug, JSON.stringify(d)]));
  const named = (slug) => path.relative(CONTENT_DIR, path.join(root, fileOf[slug] ?? `${slug}.md`)).replace(/\\/g, "/");
  const said = [
    ...docs.filter((d) => was.has(d.slug) && was.get(d.slug) !== now.get(d.slug)).map((d) => `${named(d.slug)} changed`),
    ...docs.filter((d) => !was.has(d.slug)).map((d) => `${named(d.slug)} added`),
    ...[...was.keys()].filter((slug) => !now.has(slug)).map((slug) => `${slug}.md removed`),
  ];
  return said.length > 0 ? `: ${said.join(", ")}` : "";
}

const slugs = `${banner}export const HELP_SLUGS: readonly string[] = ${JSON.stringify(docs.map((d) => d.slug), null, 2)};\n`;

if (CHECK) {
  const stale = [];
  for (const [file, text] of [[OUT_FILE, out], [SLUGS_FILE, slugs]]) {
    const committed = await fs.readFile(file, "utf8").catch(() => null);
    if (committed !== text) stale.push(path.relative(root, file));
  }
  if (stale.length > 0) {
    const pages = await driftedPages();
    console.error(
      `gen-help-content: ${stale.join(" and ")} ${stale.length > 1 ? "do" : "does"} not match content/help/${pages} — run \`pnpm gen:help\` and commit it`,
    );
    process.exit(1);
  }
  console.log(`gen-help-content: ${docs.length} docs, ${path.relative(root, OUT_FILE)} is current`);
} else {
  await fs.mkdir(path.dirname(OUT_FILE), { recursive: true });
  await fs.writeFile(OUT_FILE, out, "utf8");
  await fs.writeFile(SLUGS_FILE, slugs, "utf8");
  console.log(`gen-help-content: wrote ${docs.length} docs → ${path.relative(root, OUT_FILE)}`);
}
